"""Write local Supabase credentials without printing them or changing production .env."""

import json
import subprocess
from pathlib import Path

import structlog

from orbit_backend.logging import configure_logging
from orbit_backend.utils.enums import Environment


def main() -> None:
    """Read the running local stack and write an ignored development environment file."""
    configure_logging(Environment.DEVELOPMENT)
    root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        ["supabase", "status", "-o", "json"], cwd=root, capture_output=True, text=True
    )
    if result.returncode:
        raise SystemExit("Local Supabase is unavailable. Start Docker and run make supabase-start.")
    status = json.loads(result.stdout)
    url = status["API_URL"]
    key = status.get("PUBLISHABLE_KEY") or status["ANON_KEY"]
    path = root / ".env.development"
    path.touch(mode=0o600, exist_ok=True)
    path.chmod(0o600)
    path.write_text(
        "# Generated by make supabase-env. Local development only.\n"
        f"SUPABASE_URL={json.dumps(url)}\nSUPABASE_KEY={json.dumps(key)}\n"
    )
    structlog.get_logger(__name__).info("supabase.local_config_updated", path=str(path))


if __name__ == "__main__":
    main()
